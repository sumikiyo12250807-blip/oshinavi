NG2 = re.compile(r'あんた')
ok = True
for i, (name, body) in enumerate(POSTS, 1):
    n = len(body)
    kaigyo = re.findall(r'。(?=[^\s])', body)
    checks = [
        ('字数250-330', 250 <= n <= 330),
        ('冒頭', body.startswith('OSHINAVIの"明日発売"ピックアップ🎫')),
        ('CTA', '▼チケット情報はこちら → https://oshinavi.jp' in body),
        ('署名', '推しの"発売日"見逃さない｜OSHINAVI' in body),
        ('タグ', body.rstrip().split('\n')[-1].startswith('#')),
        ('句点直後の改行', not kaigyo),
        ('二人称なし', not NG2.search(body)),
    ]
    bad = [c for c, v in checks if not v]
    print('[%d] %-22s %3d字  %s' % (i, name, n, 'OK' if not bad else '🚨 ' + ' / '.join(bad)))
    if bad:
        ok = False

# 語の重複チェック（5本横断）
