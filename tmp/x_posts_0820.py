for _, b in POSTS:
    for w in set(re.findall(r'[ぁ-んァ-ヶ一-龠]{3,}', b)):
        words[w] += 1
dup = [(w, c) for w, c in words.items() if c >= 3 and w not in ('チケット', '一般発売', '発売', '公演', 'ピックアップ')]
