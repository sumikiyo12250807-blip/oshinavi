# -*- coding: utf-8 -*-
"""下書きから「並べる側の目線」の言い回しを消す（2026-09-04 ユーザー指摘）。

🚨消すもの＝「うちの記録では」「同じ朝に一斉に出る」のような**運営が眺めている構造の話**。
✅残すもの＝ツアーが年をまたぐ・券種が2種類ある、のような**読者に効く情報**。

「うちの記録では」は、あたしが facts.md に「会場の総数を断定しない」と書いたせいで
Fable が張った予防線。公式で裏が取れている範囲（ツアーの初日・最終日）は言い切ってよい。
- MONO NO AWARE 公式ツアー期間 2026/11/2〜2027/3/14 → 11/2が初日で正しい
- スカパラ 公式 2026/10/29〜2027/1/16 → 10/29が初日で正しい
- 佐藤竹善 Your Christmas Night 2026 は 11/22 青森〜12/26 小樽 → 12/26が最終日で正しい
"""
import io

P = "tmp/pickup0906/draft.md"
s = io.open(P, encoding="utf-8").read()

REPL = [
    # MONO NO AWARE
    ("うちの記録では初日にあたる大阪 11/2公演から始まって",
     "ツアーの初日にあたる大阪 11/2公演から始まって"),
    ("それに岐阜・静岡・愛知・三重 11/3〜R9年 2/24公演までが、同じ朝に一斉に出るの。",
     "それに岐阜・静岡・愛知・三重 11/3〜R9年 2/24公演までが、この土曜の朝に出るのよ。"),
    # 東京スカパラダイスオーケストラ
    ("埼玉 10/29公演は、うちの記録ではツアーの始まりの日にあたるわ。",
     "埼玉 10/29公演が、このツアーの始まりの日よ。"),
    # 佐藤竹善
    ("締めくくりの北海道 12/26公演は小樽 GOLDSTONEで、うちの記録ではこれがツアーの最終日。",
     "締めくくりの北海道 12/26公演は小樽 GOLDSTONE。\nこの日が最終日よ。"),
    # 深掘り
    ("その道のりを、うちに載っているぶんだけでも眺めてみるとね。",
     "今週チケットが出るぶんを眺めてみるとね。"),
    ("——うちの記録にある名前を並べただけで、こうなるの。",
     "——街ごとの箱の名前を並べただけで、こうなるの。"),
]

n = 0
for a, b in REPL:
    if a not in s:
        print("見つからない: %s" % a[:34])
        continue
    s = s.replace(a, b, 1)
    n += 1

io.open(P, "w", encoding="utf-8").write(s)
print("REPLACED=%d / %d" % (n, len(REPL)))

# 残っていないか点検
import re
left = re.findall(r"^.*(?:うちの記録|うちに載って|同じ朝に一斉|同じ朝に並ぶ).*$", s, re.M)
print("残っている運営目線の行=%d" % len(left))
for l in left:
    print("   %s" % l[:60])
