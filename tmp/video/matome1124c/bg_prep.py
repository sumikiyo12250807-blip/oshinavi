#   高さ1920に合わせて拡大（3413×1920）→ まん中 1080 を切る＝上に雲（まん中の雲）・その下は星空
import os, subprocess
import imageio_ffmpeg
D = 'C:/Users/user/oshinavi/tmp/video/matome1124c/'
B = D + 'bgf/'
os.makedirs(B, exist_ok=True)
for f in os.listdir(B):
    os.remove(B + f)
ff = imageio_ffmpeg.get_ffmpeg_exe()
vf = 'fps=30,scale=-2:1920:flags=lanczos,crop=1080:1920'   # 11/16 TikTok 白とピンクのキラキラ 251638（20.02 秒）＝すちこ 11/13「背景がくらいよ」＝元の明るさと色のまま・暗くしない・ぼかさない   # 11/14 紫の地に赤い光の粒が渦を巻く 7472（もとから暗い 19〜27＝暗くしない・粒が消えないようにぼかしは弱く）   # 11/15 おにぎり柄 227723（緑のしま・明るい 226＝0.5 倍で約 113・ぼかし 3＝柄が字の後ろでうるさくない程度）   # 11/12 水色の地に雪の結晶 97366（明るい 167＝0.6 倍で約 100・白い字が読めるように）   # 11/11 黒地に色の線の格子 158463（もとから暗い 21＝線が字の後ろでうるさくない程度に 0.55 倍・ぼかし 3＝試しのコマで線が字の後ろで明るすぎた）／11/13 夜のビル街 73197（窓の粒が字の後ろでうるさい＝ぼかし5・0.55倍）／11/10 緑〜青の波 104570（明るい 152＝0.6 倍で約 90・波の形は残す）／11/9 雨粒 222382（黒地に青い粒・拡大で大きくなる＝ぼかして半分の明るさ）／11/8 花火 97396（黒地＝暗くしない）／11/6 青い光の粒 141688（もとから黒地＝暗くしない・粒が消えないようにぼかしは弱く）
r = subprocess.run([ff, '-y', '-v', 'error', '-i', D + 'bg_src.mp4', '-vf', vf, '-q:v', '3', B + '%04d.jpg'], capture_output=True, text=True, errors='replace')
print('bg rc', r.returncode, r.stderr[-300:], 'frames', len([f for f in os.listdir(B) if f.endswith('.jpg')]))
