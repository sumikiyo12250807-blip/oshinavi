WD = '月火水木金土日'
NG = 0
for name, body in POSTS:
    n = len(body)
    errs = []
    if not (250 <= n <= 330):
        errs.append('字数 %d（250〜330の外）' % n)
    # 「。」の直後の改行。「モーニング娘。'26」の名前内だけ例外なので退避して検査する
    probe = body.replace('モーニング娘。', 'モーニングムスメ')
    for m in re.finditer('。(?!$)', probe):
        if probe[m.end():m.end() + 1] != '\n':
            errs.append('「。」のあとで改行していない: …%s' % probe[max(0, m.start() - 12):m.end() + 6].replace('\n', '⏎'))
    if 'https://oshinavi.jp' not in body:
        errs.append('URLが無い')
    if re.search(r'oshinavi\.jp[/?]', body):
        errs.append('URLに余計なものが付いている')
    if '▼チケット情報はこちら' not in body:
        errs.append('CTAの文言が違う')
    if '#OSHINAVI' not in body:
        errs.append('署名タグが無い')
    # 曜日を実カレンダーと照合（曜日文字のときだけ見る＝「10/25(大阪)」を拾わない）
    for mm in re.finditer(r'(\d{1,2})/(\d{1,2})\(([月火水木金土日])', body):
        mo, dy, w = int(mm.group(1)), int(mm.group(2)), mm.group(3)
        y = 2027 if '来年' in body[max(0, mm.start() - 4):mm.start()] else 2026
        try:
            real = WD[datetime.date(y, mo, dy).weekday()]
        except ValueError:
            errs.append('日付が存在しない %d/%d' % (mo, dy)); continue
        if real != w:
            errs.append('曜日ちがい %d/%d は%s曜（%sと書いてある）' % (mo, dy, real, w))
    print('%-22s %3d字  %s' % (name, n, 'OK' if not errs else '🚨' + ' / '.join(errs)))
    NG += len(errs)

print('\n=== 違反 %d件 ===' % NG)
