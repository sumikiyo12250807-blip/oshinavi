# -*- coding: utf-8 -*-
"""X投稿5本を「明日発売」型から「本日発売」型へ直す（8/19夜→8/20朝に回したため）。
事実（日付・時刻・会場）は変えず、時制の語だけ差し替える。
"""
import io, re, sys, glob
sys.stdout.reconfigure(encoding='utf-8')

REPL = [
    # 5本目（まとめ）
    ('明日は26件の公演で発売が始まる、大きな一日よ。', '今日は26件の公演で発売が始まる、大きな一日よ。'),
    ('寝る前にOSHINAVIをのぞいて、推しの名前で検索してごらんなさい。\n明日の朝、慌てないためよ。',
     '出かける前にOSHINAVIをのぞいて、推しの名前で検索してごらんなさい。\n10時が来る前に、狙いを決めておくのよ。'),
    ('8/20(木) 10:00から続々発売！', '本日8/20(木) 10:00から続々発売！'),
    # 1本目
    ('一般発売は8/20(木)10:00スタート。', '一般発売は本日10:00スタート。'),
    # 2本目
    ('一般発売は8/20(木)10:00。', '一般発売は本日10:00。'),
    # 3本目
    ('8/20(木)11:00に始まるのはプレリザーブ。', '本日11:00に始まるのはプレリザーブ。'),
    # 4本目
    ('一般発売は8/20(木)、昼12:00よ。', '一般発売は本日、昼12:00よ。'),
    # 見出し行（1〜4本目）
    ('8/20(木) 10:00発売！', '本日8/20(木) 10:00発売！'),
    ('8/20(木) 11:00発売！', '本日8/20(木) 11:00発売！'),
    ('8/20(木) 12:00発売！', '本日8/20(木) 12:00発売！'),
]

for p in sorted(glob.glob('tmp/post0820_*.txt')):
    t = io.open(p, encoding='utf-8').read()
    before = t
    for a, b in REPL:
        t = t.replace(a, b)
    if t != before:
        io.open(p, 'w', encoding='utf-8', newline='\n').write(t)
    print('%s %d字 %s' % (p, len(t), '（直した）' if t != before else '（変更なし）'))
