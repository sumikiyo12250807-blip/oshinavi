# -*- coding: utf-8 -*-
"""X(Twitter)の重み付き文字数を計算。上限280(=日本語140字)。
weight: 半角(0x0000-0x10FF ほか特定範囲)=1、それ以外(CJK/全角/絵文字)=2。"""
import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

def w1(cp):
    return (cp <= 0x10FF) or (0x2000 <= cp <= 0x200D) or (0x2010 <= cp <= 0x201F) or (0x2032 <= cp <= 0x2037)

def weighted(s):
    total = 0
    for ch in s:
        total += 1 if w1(ord(ch)) else 2
    return total

