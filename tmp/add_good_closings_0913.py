# -*- coding: utf-8 -*-
"""X_SCRIPT.md に「ユーザーが良いと言った締め」を足す（2026-09-13）。
Fable が読むのは X_SCRIPT.md と素材だけなので、効いた型はここに置く。
"""
import io
import sys

sys.stdout.reconfigure(encoding='utf-8')
p = 'X_SCRIPT.md'
s = io.open(p, encoding='utf-8', newline='').read()

anchor = '## 書かないもの'
add = '''## 🆕【2026-09-13 ユーザーが「すごくいい」と言った締め】この型に寄せる

> 「**いい締めの言葉もある　あなたの街はいつかしら　とか　あなたの手で取りに行って　はすごくいいと思うの**」

```
11月のZepp、あなたの街の番はいつかしら。
明日の11時、忘れないでね。
```
```
推しに会える日は、こういう月曜の朝に決まるものなのよ。
10時と11時、あなたの手で取りにいって。
```

**なぜ効くのか（次に書くときの手がかり）**
- **読む人を主語にしている**＝「あなたの街」「あなたの手で」。サイトでも発売でもなく、**その人の番**の話になる。
- **問いかけで終わる／動作で終わる**＝「いつかしら」と投げる、「取りにいって」と手を動かさせる。
  説明でも案内でもない。
- ⚠️ここで使ってよい二人称は「**あなた**」（[[feedback_tone_onee]]＝禁止なのは別の言い方だけ）。

同じ日に**不自然**と言われたのが「**ひと笑いぶんを取りにいって**」＝
「ひと◯◯ぶん」を数えられないものに付けると日本語にならない。
（「ひと押しだけしておいて」は**OK**＝押すのは1回と数えられるから。ユーザー「ひと押しの方も使っていい」）

🚨**良いと言われた締めは、次の号でも同じ言い回しを使い回さない**（[[feedback_x_post_method_0825]]＝
締めは毎回違う言葉）。**寄せるのは「型」であって、文そのものではない。**

'''
assert anchor in s, '目印が見つからない'
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace(anchor, add + anchor, 1))
print('X_SCRIPT.md に足したわ')
