def xlen(s):
    n = 0
    for ch in s:
        o = ord(ch)
        if o > 0x1F000 or (0x3000 <= o <= 0x9FFF) or (0xFF00 <= o <= 0xFFEF) or (0x2E80 <= o <= 0x31FF):
            n += 2
        else:
            n += 1
    return n


